#!/usr/bin/env bash
set -euo pipefail

source /etc/openkache-fd.env

FD_ROOT=/opt/openkache-fd
FD_DATA_MOUNT="${FD_DATA_MOUNT:-/mnt/openkache-fd-data}"
FD_STATE="${FD_STATE_ROOT:-$FD_DATA_MOUNT/state}"
FD_RUNS="$FD_STATE/runs"
FD_CAMPAIGN="$FD_STATE/campaign"
FD_S3_PREFIX="s3://$FD_BUCKET/$FD_EXPERIMENT_ID"
FD_UNIT=openkache-fd-node.service

mkdir -p "$FD_RUNS" "$FD_CAMPAIGN"

metadata() {
  local path=$1
  local token
  token=$(curl --fail --silent --show-error --max-time 2 \
    -X PUT -H 'X-aws-ec2-metadata-token-ttl-seconds: 60' \
    http://169.254.169.254/latest/api/token)
  curl --fail --silent --show-error --max-time 2 \
    -H "X-aws-ec2-metadata-token: $token" \
    "http://169.254.169.254/latest/meta-data/$path"
}

manifest_path() {
  printf '%s/%s/run.env\n' "$FD_RUNS" "$1"
}

download_manifest() {
  local run_id=$1
  local run_dir="$FD_RUNS/$run_id"
  mkdir -p "$run_dir"
  aws s3 cp --region "$AWS_REGION" \
    "$FD_S3_PREFIX/manifests/$run_id.env" "$run_dir/run.env" >/dev/null
}

load_manifest() {
  local run_id=$1
  download_manifest "$run_id"
  # The manifest is generated by the trusted coordinator with shell-escaped values.
  # shellcheck disable=SC1090
  source "$(manifest_path "$run_id")"
  if [[ "$RUN_ID" != "$run_id" ]]; then
    echo "manifest run id mismatch: expected=$run_id actual=$RUN_ID" >&2
    exit 1
  fi
}

write_json_event() {
  local file=$1 event=$2 subject=$3
  jq -cn \
    --arg event "$event" \
    --arg fault "$FAULT" \
    --arg subject "$subject" \
    --arg wallTime "$(date -u +%Y-%m-%dT%H:%M:%S.%NZ)" \
    --argjson wallEpochNanos "$(date +%s%N)" \
    '{event:$event,fault:$fault,subject:$subject,wallTime:$wallTime,wallEpochNanos:$wallEpochNanos}' \
    >>"$file"
}
